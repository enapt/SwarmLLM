/// Direct split-model streaming generation.
///
/// Same fast path as split_non_stream_response but streams tokens via SSE.
/// Builds the prompt from the model's own chat template to avoid template mismatch.
async fn split_stream_response(
    state: AppState,
    request_id: String,
    created: i64,
    model_name: String,
    messages: Vec<ChatMessage>,
    params: SamplingParams,
    model_id: crate::types::ModelId,
) -> Sse<impl Stream<Item = Result<Event, Infallible>>> {
    let (tx, rx) = tokio::sync::mpsc::channel::<StreamEvent>(64);
    let request_id_inner = request_id.clone();

    tokio::spawn(async move {
        let request_id = request_id_inner;
        // Send initial role delta
        let stream_start = std::time::Instant::now();
        let mut token_count: u64 = 0;

        if !send_role_preamble(&tx).await {
            tracing::debug!("DIAG: split stream role delta send failed — client disconnected");
            return;
        }

        // Spawn split-model generation and get token receiver
        let mut token_rx =
            match spawn_split_stream(&state, &model_id, &messages, params, &request_id) {
                Some(rx) => rx,
                None => {
                    tracing::debug!(model_id = %model_id, "DIAG: split stream model not found");
                    let _ = tx.send(StreamEvent::Done).await;
                    return;
                }
            };

        // Forward streaming tokens from the worker to SSE events
        let mut finish = "length".to_string();
        while let Some(event) = token_rx.recv().await {
            if let Some(fr) = &event.finish_reason {
                finish = fr.clone();
                break;
            }
            token_count += 1;
            if tx
                .send(StreamEvent::Delta {
                    content: Some(event.text),
                    role: None,
                    finish_reason: None,
                })
                .await
                .is_err()
            {
                tracing::warn!(
                    token_count,
                    elapsed_ms = stream_start.elapsed().as_millis() as u64,
                    "DIAG: split stream client disconnected mid-decode"
                );
                return;
            }
        }

        tracing::info!(
            model_id = %model_id,
            token_count,
            finish = %finish,
            "DIAG: split stream decode loop complete (subprocess)"
        );

        // Send finish
        if tx
            .send(StreamEvent::Delta {
                content: None,
                role: None,
                finish_reason: Some(finish),
            })
            .await
            .is_err()
        {
            tracing::debug!(token_count, "DIAG: split stream finish delta send failed");
        }
        if tx.send(StreamEvent::Done).await.is_err() {
            tracing::debug!("DIAG: split stream Done send failed — client disconnected");
        }
        let elapsed = stream_start.elapsed();
        tracing::info!(
            elapsed_ms = elapsed.as_millis() as u64,
            token_count,
            "DIAG: split stream completed"
        );
    });

    stream_events_to_sse(rx, request_id, created, model_name, None)
}

async fn stream_response(
    state: AppState,
    request_id: String,
    created: i64,
    model_name: String,
    prompt: String,
    params: SamplingParams,
) -> Sse<impl Stream<Item = Result<Event, Infallible>>> {
    let (tx, rx) = tokio::sync::mpsc::channel::<StreamEvent>(64);

    // Spawn generation in background
    tokio::spawn(async move {
        let stream_start = std::time::Instant::now();
        let mut token_count: u64 = 0;

        // Send initial role delta
        if !send_role_preamble(&tx).await {
            tracing::debug!("DIAG: local stream role delta send failed — client disconnected");
            return;
        }

        let mut executor = state.executor.lock().await;
        let result = executor.generate_stream(&prompt, &params, |token| {
            token_count += 1;
            let send_result = tx.try_send(StreamEvent::Delta {
                content: Some(token.to_string()),
                role: None,
                finish_reason: None,
            });
            if send_result.is_err() {
                tracing::warn!(
                    token_count,
                    "DIAG: local stream token send failed — channel full or client disconnected"
                );
            }
            send_result.is_ok()
        });

        // Send finish reason
        let finish = match result {
            Ok(r) => r.finish_reason.as_str().to_string(),
            Err(ref e) => {
                tracing::error!(error = %e, "DIAG: local stream generate_stream error");
                "error".to_string()
            }
        };
        if tx
            .send(StreamEvent::Delta {
                content: None,
                role: None,
                finish_reason: Some(finish.clone()),
            })
            .await
            .is_err()
        {
            tracing::debug!(token_count, finish_reason = %finish, "DIAG: local stream finish send failed");
        }
        if tx.send(StreamEvent::Done).await.is_err() {
            tracing::debug!("DIAG: local stream Done send failed — client disconnected");
        }
        let elapsed = stream_start.elapsed();
        tracing::info!(
            elapsed_ms = elapsed.as_millis() as u64,
            token_count,
            "DIAG: local stream completed"
        );
    });

    stream_events_to_sse(rx, request_id, created, model_name, None)
}

/// Convert a StreamEvent receiver into an SSE stream of OpenAI-format chat completion chunks.
fn stream_events_to_sse(
    rx: tokio::sync::mpsc::Receiver<StreamEvent>,
    request_id: String,
    created: i64,
    model_name: String,
    session_id: Option<String>,
) -> Sse<impl futures::Stream<Item = Result<Event, Infallible>>> {
    let mut json_buf = Vec::with_capacity(512);
    let stream = tokio_stream::wrappers::ReceiverStream::new(rx).map(move |event| match event {
        StreamEvent::Delta {
            content,
            role,
            finish_reason,
        } => {
            let sid = if finish_reason.is_some() {
                session_id.clone()
            } else {
                None
            };
            let chunk = ChatCompletionChunk {
                id: request_id.clone(),
                object: "chat.completion.chunk",
                created,
                model: model_name.clone(),
                choices: vec![ChunkChoice {
                    index: 0,
                    delta: Delta {
                        role,
                        content,
                        tool_calls: None,
                    },
                    finish_reason,
                    logprobs: None,
                }],
                session_id: sid,
            };
            json_buf.clear();
            let json = if serde_json::to_writer(&mut json_buf, &chunk).is_ok() {
                String::from_utf8(json_buf.clone()).unwrap_or_default()
            } else {
                String::new()
            };
            Ok::<_, Infallible>(Event::default().data(json))
        }
        StreamEvent::Error { message } => {
            let error_json = serde_json::json!({
                "error": {
                    "message": message,
                    "type": "server_error"
                }
            });
            Ok(Event::default().data(serde_json::to_string(&error_json).unwrap_or_default()))
        }
        StreamEvent::Done => Ok(Event::default().data("[DONE]")),
    });
    Sse::new(stream).keep_alive(
        KeepAlive::new().interval(std::time::Duration::from_secs(SSE_KEEPALIVE_INTERVAL_SECS)),
    )
}

enum StreamEvent {
    Delta {
        content: Option<String>,
        role: Option<String>,
        finish_reason: Option<String>,
    },
    Error {
        message: String,
    },
    Done,
}

/// Send the initial `role: "assistant"` delta that opens the streaming response.
/// Returns `false` if the client has already disconnected.
async fn send_role_preamble(tx: &tokio::sync::mpsc::Sender<StreamEvent>) -> bool {
    tx.send(StreamEvent::Delta {
        content: None,
        role: Some("assistant".into()),
        finish_reason: None,
    })
    .await
    .is_ok()
}

/// GET /v1/models
///
/// Lists models usable for inference. A model is usable when all its layers
/// are covered by at least one node in the network — no single node needs
/// the full shard set. Models still propagating across the network (some
/// layers uncovered) are excluded here but visible in the admin dashboard.
pub async fn list_models(State(state): State<AppState>) -> Json<ModelListResponse> {
    let mut data = vec![];
    let mut seen = std::collections::HashSet::new();

    // Use cached model info (lock-free, no executor contention)
    if let Some(info) = state.shared_state.loaded_model_info.read().await.as_ref() {
        seen.insert(info.name.clone());
        let slug = crate::types::slugify_model_name(&info.name);
        seen.insert(slug.clone());

        // Find the registry manifest for this model so we can use its canonical ID
        // and mark it as seen (prevents duplicates in section 2).
        let manifest = state
            .shared_state
            .model_registry
            .resolve_manifest_by_name(&info.name);

        let model_id = if let Some(ref m) = manifest {
            seen.insert(m.id.0.clone());
            m.id.0.clone()
        } else {
            slug
        };

        data.push(ModelInfo {
            id: model_id,
            object: "model",
            created: chrono::Utc::now().timestamp(),
            owned_by: "local".into(),
        });
    }

    // Include models from the registry if all layers are covered network-wide
    for manifest in state.shared_state.model_registry.models() {
        let id = manifest.id.0.clone();
        if seen.contains(&id) {
            continue;
        }
        if all_shards_available(&state, &id) {
            seen.insert(id.clone());
            data.push(ModelInfo {
                id,
                object: "model",
                created: manifest.publish_date.timestamp(),
                owned_by: "network".into(),
            });
        }
    }

    Json(ModelListResponse {
        object: "list",
        data,
    })
}

