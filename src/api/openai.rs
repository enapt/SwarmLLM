/// Maximum allowed base64-encoded image size (20MB decoded).
const MAX_IMAGE_BASE64_BYTES: usize = 20 * 1024 * 1024;

impl ApiChatMessage {
    /// Convert to the internal `ChatMessage` type, decoding any base64 images.
    pub fn to_chat_message(&self) -> Result<ChatMessage, crate::error::SwarmError> {
        let (text, images) = match &self.content {
            MessageContent::Text(s) => (s.clone(), vec![]),
            MessageContent::Parts(parts) => {
                let mut text_parts = Vec::new();
                let mut images = Vec::new();
                for part in parts {
                    match part {
                        ContentPart::Text { text } => text_parts.push(text.clone()),
                        ContentPart::ImageUrl { image_url } => {
                            let img = decode_image_url(&image_url.url)?;
                            images.push(img);
                        }
                    }
                }
                (text_parts.join("\n"), images)
            }
        };

        Ok(ChatMessage {
            role: self.role.clone(),
            content: text,
            images,
        })
    }
}

impl ChatCompletionRequest {
    /// Convert API messages to internal ChatMessage format, decoding images.
    /// When tools or response_format are provided, injects system message(s).
    pub fn to_internal_messages(&self) -> Result<Vec<ChatMessage>, crate::error::SwarmError> {
        let mut messages: Vec<ChatMessage> = self
            .messages
            .iter()
            .map(|m| m.to_chat_message())
            .collect::<Result<_, _>>()?;

        // Inject structured output instructions
        if let Some(ref fmt) = self.response_format {
            let instruction = match fmt {
                ResponseFormat::Text => None,
                ResponseFormat::JsonObject => Some(
                    "You must respond with valid JSON only. Do not include any text \
                     outside the JSON object. Do not use markdown code blocks."
                        .to_string(),
                ),
                ResponseFormat::JsonSchema { json_schema } => {
                    let schema_str = serde_json::to_string_pretty(&json_schema.schema)
                        .unwrap_or_else(|_| json_schema.schema.to_string());
                    Some(format!(
                        "You must respond with valid JSON that conforms to the following schema. \
                         Do not include any text outside the JSON object. Do not use markdown code blocks.\n\n\
                         Schema name: {}\n\
                         Schema:\n{schema_str}",
                        json_schema.name
                    ))
                }
            };
            if let Some(inst) = instruction {
                messages.insert(
                    0,
                    ChatMessage {
                        role: crate::types::Role::System,
                        content: inst,
                        images: vec![],
                    },
                );
            }
        }

        // Inject tool definitions as a system message prefix
        if let Some(ref tools) = self.tools {
            if !tools.is_empty() {
                let tool_desc = format_tool_system_prompt(tools);
                messages.insert(
                    0,
                    ChatMessage {
                        role: crate::types::Role::System,
                        content: tool_desc,
                        images: vec![],
                    },
                );
            }
        }

        Ok(messages)
    }
}

/// Format tool definitions into a system prompt that instructs the model
/// to output tool calls in a structured JSON format.
fn format_tool_system_prompt(tools: &[ToolDefinition]) -> String {
    let mut prompt = String::from(
        "You have access to the following tools. To call a tool, respond with a JSON object \
         in the following format:\n\
         {\"tool_calls\": [{\"id\": \"call_<unique_id>\", \"type\": \"function\", \
         \"function\": {\"name\": \"<function_name>\", \"arguments\": \"<json_args>\"}}]}\n\n\
         Available tools:\n",
    );
    for tool in tools {
        prompt.push_str(&format!("- {}", tool.function.name));
        if let Some(ref desc) = tool.function.description {
            prompt.push_str(&format!(": {desc}"));
        }
        prompt.push('\n');
        if let Some(ref params) = tool.function.parameters {
            prompt.push_str(&format!("  Parameters: {params}\n"));
        }
    }
    prompt
}

/// Decode a base64 data URI image to raw RGB pixels.
fn decode_image_url(url: &str) -> Result<ImageData, crate::error::SwarmError> {
    let base64_data = if let Some(rest) = url.strip_prefix("data:") {
        if let Some(comma_pos) = rest.find(',') {
            let header = &rest[..comma_pos];
            if !header.contains("base64") {
                return Err(crate::error::SwarmError::Validation(
                    "Only base64 data URIs are supported for image_url".into(),
                ));
            }
            &rest[comma_pos + 1..]
        } else {
            return Err(crate::error::SwarmError::Validation(
                "Invalid data URI format".into(),
            ));
        }
    } else {
        return Err(crate::error::SwarmError::Validation(
            "Only data: URIs are supported for image_url (not remote URLs)".into(),
        ));
    };

    if base64_data.len() > MAX_IMAGE_BASE64_BYTES * 4 / 3 + 4 {
        return Err(crate::error::SwarmError::Validation(format!(
            "Image too large (max {}MB)",
            MAX_IMAGE_BASE64_BYTES / (1024 * 1024)
        )));
    }

    use base64::Engine;
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(base64_data)
        .map_err(|e| crate::error::SwarmError::Validation(format!("Invalid base64 image: {e}")))?;

    if bytes.len() > MAX_IMAGE_BASE64_BYTES {
        return Err(crate::error::SwarmError::Validation(format!(
            "Decoded image too large: {}MB (max {}MB)",
            bytes.len() / (1024 * 1024),
            MAX_IMAGE_BASE64_BYTES / (1024 * 1024)
        )));
    }

    let img = image::load_from_memory(&bytes).map_err(|e| {
        crate::error::SwarmError::Validation(format!("Failed to decode image: {e}"))
    })?;

    let rgb = img.to_rgb8();
    let (width, height) = (rgb.width(), rgb.height());

    Ok(ImageData {
        rgb_bytes: rgb.into_raw(),
        width,
        height,
    })
}

#[derive(Debug, Serialize, Deserialize)]
#[serde(untagged)]
pub enum StopSequence {
    Single(String),
    Multiple(Vec<String>),
}

fn default_temperature() -> f32 {
    0.7
}
fn default_top_p() -> f32 {
    0.9
}
fn default_max_tokens() -> u32 {
    2048
}

impl ChatCompletionRequest {
    fn to_sampling_params(&self) -> SamplingParams {
        let stop = match &self.stop {
            Some(StopSequence::Single(s)) => vec![s.clone()],
            Some(StopSequence::Multiple(v)) => v.clone(),
            None => vec![],
        };
        SamplingParams {
            // Clamp temperature to [0.0, 2.0] to prevent invalid values
            temperature: self.temperature.clamp(0.0, 2.0),
            // Clamp top_p to (0.0, 1.0]
            top_p: self.top_p.clamp(f32::EPSILON, 1.0),
            top_k: DEFAULT_TOP_K,
            max_tokens: self.max_tokens.clamp(1, DEFAULT_MAX_TOKENS),
            stop,
            frequency_penalty: self.frequency_penalty.clamp(-2.0, 2.0),
            presence_penalty: self.presence_penalty.clamp(-2.0, 2.0),
            logprobs: self.logprobs,
            top_logprobs: self.top_logprobs.unwrap_or(0).min(20),
        }
    }
}

