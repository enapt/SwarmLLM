/// POST /v1/chat/completions
/// Validate and sanitize a chat completion request.
/// Checks session_id, model, messages, temperature, content sizes, tools, stop sequences.
/// Binds session_id to caller's API key to prevent cross-user KV-cache hijacking.
fn validate_chat_request(
    req: &mut ChatCompletionRequest,
    headers: &axum::http::HeaderMap,
) -> Result<(), ApiError> {
    // Validate session_id length to prevent memory abuse
    if let Some(ref sid) = req.session_id {
        if sid.len() > 256 {
            return Err(ApiError(crate::error::SwarmError::Validation(
                "session_id too long (max 256 chars)".into(),
            )));
        }
    }

    // Bind session_id to the caller's API key so different users cannot
    // hijack each other's KV-cache sessions by guessing session IDs.
    if let Some(ref mut sid) = req.session_id {
        let api_key = super::extract_bearer_token(headers);
        let key_hash = &blake3::hash(api_key.as_bytes()).to_hex()[..16];
        *sid = format!("{}:{}", key_hash, sid);
    }

    super::validate_common_params(req.model.len(), req.messages.len(), req.temperature.into())?;

    // SEC: Cap individual message content size and total prompt size
    super::validate_content_size(req.messages.iter().map(|msg| {
        match &msg.content {
            MessageContent::Text(s) => s.len(),
            MessageContent::Parts(parts) => parts
                .iter()
                .map(|p| match p {
                    ContentPart::Text { text } => text.len(),
                    ContentPart::ImageUrl { image_url } => image_url.url.len(),
                })
                .sum(),
        }
    }))?;

    if let Some(ref tools) = req.tools {
        super::validate_tools(
            tools,
            |t| Some(t.function.name.as_str()),
            |t| t.function.description.as_deref(),
            |t| t.function.parameters.as_ref().map(|p| p.to_string().len()),
        )?;
    }

    if let Some(ref adapter) = req.lora_adapter {
        if adapter.len() > 256 {
            return Err(ApiError(crate::error::SwarmError::Validation(
                "lora_adapter name too long (max 256 chars)".into(),
            )));
        }
        if adapter.contains("..") || adapter.contains('/') || adapter.contains('\\') {
            return Err(ApiError(crate::error::SwarmError::Validation(
                "lora_adapter contains invalid characters".into(),
            )));
        }
    }

    match &req.stop {
        Some(crate::api::openai::StopSequence::Multiple(v)) => {
            super::validate_stop_sequences(v)?;
        }
        Some(crate::api::openai::StopSequence::Single(s)) => {
            super::validate_stop_sequences(std::slice::from_ref(s))?;
        }
        None => {}
    }

    Ok(())
}

/// Try proxying a chat completion request to a configured cloud provider.
async fn try_cloud_proxy(
    state: &AppState,
    req: &ChatCompletionRequest,
) -> Result<Option<axum::response::Response>, ApiError> {
    // Claude subscription: proxy through local CLI subprocess (higher priority than API key)
    #[cfg(feature = "claude-subscription")]
    if let Some(sub_config) =
        crate::api::claude_sub::try_get_claude_subscription(state, &req.model).await
    {
        tracing::info!(model = %req.model, "DIAG: openai proxying via claude subscription subprocess");
        let body = serde_json::to_value(req).map_err(|e| {
            ApiError(crate::error::SwarmError::Validation(format!(
                "serialize request: {e}"
            )))
        })?;
        return crate::api::claude_sub::proxy_via_subprocess_openai(&sub_config, &body)
            .await
            .map(Some);
    }

    let body = serde_json::to_value(req).map_err(|e| {
        ApiError(crate::error::SwarmError::Validation(format!(
            "serialize request: {e}"
        )))
    })?;
    crate::api::providers::try_proxy_openai(state, &body, req.stream).await
}

pub async fn chat_completions(
    State(state): State<AppState>,
    headers: axum::http::HeaderMap,
    crate::api::server::JsonBody(mut req): crate::api::server::JsonBody<ChatCompletionRequest>,
) -> Result<axum::response::Response, ApiError> {
    validate_chat_request(&mut req, &headers)?;

    // Convert API messages to internal format (decode base64 images if present)
    let internal_messages = req.to_internal_messages().map_err(ApiError)?;

    let request_id = format!("swarm-{}", uuid::Uuid::new_v4().simple());
    let created = chrono::Utc::now().timestamp();

    // Track requests made by this node
    super::increment_requests_made(&state.shared_state);

    // Emit activity event for inference request
    {
        let mname = state
            .shared_state
            .model_registry
            .get_manifest(&crate::types::ModelId(req.model.clone()))
            .map(|m| m.name.clone());
        let display = mname.as_deref().unwrap_or(&req.model);
        let max_tok = req.max_tokens;
        let msg_count = req.messages.len();
        let prompt_preview: String = req
            .messages
            .last()
            .map(|m| {
                let content = match &m.content {
                    crate::api::openai::MessageContent::Text(s) => s.clone(),
                    crate::api::openai::MessageContent::Parts(parts) => parts
                        .iter()
                        .filter_map(|p| match p {
                            crate::api::openai::ContentPart::Text { text } => Some(text.as_str()),
                            _ => None,
                        })
                        .collect::<Vec<_>>()
                        .join(" "),
                };
                if content.len() > 60 {
                    format!(
                        "{}...",
                        &content[..content
                            .char_indices()
                            .take_while(|(i, _)| *i < 57)
                            .last()
                            .map(|(i, c)| i + c.len_utf8())
                            .unwrap_or(57)]
                    )
                } else {
                    content
                }
            })
            .unwrap_or_default();
        state.shared_state.emit_activity(
            crate::daemon::state::ActivityEvent::new(
                "inference",
                "inference_request",
                format!(
                    "Inference request on {} — {} message{}, max {} tokens{}",
                    display,
                    msg_count,
                    if msg_count != 1 { "s" } else { "" },
                    max_tok,
                    if !prompt_preview.is_empty() {
                        format!(": \"{}\"", prompt_preview)
                    } else {
                        String::new()
                    }
                ),
            )
            .with_model(req.model.clone())
            .with_detail_num(max_tok as i64),
        );
    }

    // Resolve "auto" alias and display-name → registry-ID mapping.
    {
        let resolved = resolve_model_for_inference(&state, &req.model).await;
        if resolved != req.model {
            tracing::info!(original = %req.model, resolved_model = %resolved, "Resolved model alias");
            req.model = resolved;
        }
    }

    let image_count: usize = internal_messages.iter().map(|m| m.images.len()).sum();
    tracing::info!(
        request_id = %request_id,
        model = %req.model,
        messages = internal_messages.len(),
        images = image_count,
        stream = req.stream,
        "Chat completion request"
    );

    // Get model name — try loaded_model_info cache first, then manifest registry.
    let model_name = resolve_model_name(&state, &req.model).await;

    // No local full-model executor — use distributed inference or forward.
    // Nodes are NOT required to have all shards. Any node can initiate inference
    // as long as the network collectively covers all layers.
    // The `x-swarm-forwarded` header prevents infinite forwarding loops between nodes.
    // Only trust this header from internal requests (authenticated with internal token).
    // Middleware already validates that x-swarm-forwarded only passes from known peer IPs
    // or loopback with valid internal token, so we just check presence here.
    let is_forwarded = headers.get("x-swarm-forwarded").is_some();

    if model_name.is_none() {
        // Priority 1: Check if all layers are covered across the network for
        // distributed inference. The local node may have zero, some, or all shards —
        // it doesn't matter as long as the network covers every layer.
        if all_shards_available(&state, &req.model) {
            tracing::info!(
                request_id = %request_id,
                model = %req.model,
                stream = req.stream,
                "All layers covered across network — using distributed inference"
            );

            if let Some(router_tx) = &state.router_tx {
                return dispatch_inference(
                    router_tx.clone(),
                    &state,
                    &req,
                    internal_messages.clone(),
                    request_id,
                    created,
                )
                .await;
            } else {
                return Err(ApiError(crate::error::SwarmError::NoModelLoaded));
            }
        }

        // Priority 2: Forward to a peer that hosts shards for this model.
        // That peer can handle inference locally or build its own pipeline.
        if !is_forwarded {
            if let Some(peer_url) = find_peer_with_model(&state, &req.model) {
                tracing::info!(
                    request_id = %request_id,
                    peer_url = %peer_url,
                    "Forwarding request to peer"
                );
                return forward_to_peer(&peer_url, &req, req.stream).await;
            }
        }

        // Cloud provider fast-path: if the model matches a configured cloud provider,
        // route immediately without cold-start waiting. Cloud models are never local.
        if let Some(response) = try_cloud_proxy(&state, &req).await? {
            return Ok(response);
        }

        // Fast-reject: if the model has no manifest but other models ARE registered,
        // the user likely mistyped. Return ModelNotAvailable immediately instead of
        // wasting 10 seconds on cold-start polling. When NO models are registered,
        // fall through to the cold-start wait (node may still be starting up).
        {
            let model_id = crate::types::ModelId(req.model.clone());
            let registry = &state.shared_state.model_registry;
            if registry.get_manifest(&model_id).is_none() && !registry.models().is_empty() {
                return Err(ApiError(registry.model_not_found_error(&model_id)));
            }
        }

        // Cold-start wait: shard announcements may still be propagating.
        // Poll for up to 10 seconds before giving up.
        // Semaphore prevents unbounded pile-up under burst traffic.
        let _cold_permit = match COLD_START_SEMAPHORE.try_acquire() {
            Ok(permit) => permit,
            Err(_) => {
                tracing::warn!(
                    request_id = %request_id,
                    model = %req.model,
                    "Cold-start wait slots full — returning 503 immediately"
                );
                return Err(ApiError(crate::error::SwarmError::NoModelLoaded));
            }
        };
        let max_polls = COLD_START_WAIT_SECS * 2; // 500ms intervals
        for attempt in 1..=max_polls {
            tokio::time::sleep(std::time::Duration::from_millis(500)).await;
            // Re-check distributed inference availability
            if all_shards_available(&state, &req.model) {
                tracing::info!(
                    request_id = %request_id,
                    model = %req.model,
                    wait_ms = attempt * 500,
                    "Model became available after cold-start wait"
                );
                if let Some(router_tx) = &state.router_tx {
                    return dispatch_inference(
                        router_tx.clone(),
                        &state,
                        &req,
                        internal_messages.clone(),
                        request_id,
                        created,
                    )
                    .await;
                }
                break;
            }
            // Re-check peer forwarding
            if !is_forwarded {
                if let Some(peer_url) = find_peer_with_model(&state, &req.model) {
                    tracing::info!(
                        request_id = %request_id,
                        peer_url = %peer_url,
                        wait_ms = attempt * 500,
                        "Found peer after cold-start wait"
                    );
                    return forward_to_peer(&peer_url, &req, req.stream).await;
                }
            }
        }

        // Cloud provider fallback: proxy to configured cloud provider if model matches
        if let Some(response) = try_cloud_proxy(&state, &req).await? {
            return Ok(response);
        }

        return Err(ApiError(crate::error::SwarmError::NoModelLoaded));
    }

    let model_name =
        model_name.expect("model_name guaranteed Some — None case returns early above");
    let params = req.to_sampling_params();

    // Fast path: if we have a complete local split model (all layers), generate directly.
    // This avoids the distributed pipeline overhead (per-token segment coordination,
    // activation serialization, mutex per token). ~5-10x faster for local inference.
    // Uses the pre-computed is_complete flag — no model mutex needed.
    // Look up by the REQUESTED model ID, not just the first entry.
    // NOTE: prompt is built inside split_*_response using the model's own chat template,
    // avoiding template mismatch (e.g. `<|assistant|>` prefix leak) and the unnecessary
    // loaded_model_info.read().await before the split path.
    let requested_mid = crate::types::ModelId(req.model.clone());
    let has_local_split_model = state.shared_state.has_complete_split_model(&requested_mid);

    if has_local_split_model {
        if req.stream {
            return Ok(split_stream_response(
                state,
                request_id,
                created,
                model_name,
                internal_messages.clone(),
                params,
                requested_mid.clone(),
            )
            .await
            .into_response());
        } else {
            return split_non_stream_response(
                state,
                request_id,
                created,
                model_name,
                internal_messages.clone(),
                params,
                requested_mid.clone(),
            )
            .await;
        }
    }

    // Build prompt for non-split paths (distributed inference + direct executor).
    // Uses loaded_model_info first; falls back to GGUF header on disk for
    // distributed-only nodes that have no local model but do have the probe.
    let prompt = {
        let (tmpl, bos, eos) = super::resolve_chat_template(&state, &req.model).await;
        chat_template::build_prompt(&internal_messages, tmpl.as_deref(), &bos, &eos)
    };

    // Distributed inference: network covers all layers across multiple nodes.
    let peers_have_shards = all_shards_available(&state, &req.model)
        || state.shared_state.config.inference.shard_range.is_some();
    if peers_have_shards {
        if let Some(router_tx) = &state.router_tx {
            return dispatch_inference(
                router_tx.clone(),
                &state,
                &req,
                internal_messages.clone(),
                request_id,
                created,
            )
            .await;
        }
    }

    if req.stream {
        // Streaming: use direct executor path for real token-by-token SSE
        Ok(
            stream_response(state, request_id, created, model_name, prompt, params)
                .await
                .into_response(),
        )
    } else if let Some(router_tx) = &state.router_tx {
        // Non-streaming: route through InferenceRouter for priority queueing
        router_inference(
            router_tx.clone(),
            &req,
            internal_messages,
            request_id,
            created,
        )
        .await
    } else {
        Err(crate::error::ApiError(
            crate::error::SwarmError::ServiceUnavailable(
                "Inference router not available".to_string(),
            ),
        ))
    }
}

/// Find a peer that hosts shards for this model and return its HTTP base URL.
/// This is a fallback for when not all layers are covered network-wide — the
/// peer may be able to handle the request directly or assemble its own pipeline.
fn find_peer_with_model(state: &AppState, model: &str) -> Option<String> {
    for entry in state.shared_state.peer_registry.iter() {
        let peer = entry.value();
        if let Some(ref cap) = peer.capability {
            let has_model = cap.hosted_shards.iter().any(|s| s.model_id.0 == model);
            if has_model {
                if let Some(url) = peer_http_url(peer) {
                    return Some(url);
                }
            }
        }
    }
    None
}

/// Short-lived per-model TTL for the `all_shards_available` cache. Kept tiny
/// to stay consistent with shard announcement propagation delay.
const SHARD_AVAIL_CACHE_TTL_MS: u64 = 100;

/// Check if all layers for a model are covered across the network (for distributed inference).
/// This does NOT require any single node to have all shards — it only requires that every
/// shard has at least one holder somewhere in the network so the pipeline scheduler can
/// assemble a complete pipeline across multiple nodes.
pub fn all_shards_available(state: &AppState, model_name: &str) -> bool {
    // Short-lived per-model cache to avoid repeated ModelId/ShardId allocations
    use std::sync::LazyLock;
    static CACHE: LazyLock<dashmap::DashMap<String, (std::time::Instant, bool)>> =
        LazyLock::new(dashmap::DashMap::new);
    let ttl = std::time::Duration::from_millis(SHARD_AVAIL_CACHE_TTL_MS);
    if let Some(entry) = CACHE.get(model_name) {
        if entry.0.elapsed() < ttl {
            return entry.1;
        }
    }

    let result = all_shards_available_inner(state, model_name);
    // Evict stale entries instead of clearing entire cache (prevents thundering herd)
    const SHARD_AVAIL_CACHE_MAX: usize = 1_000;
    if CACHE.len() > SHARD_AVAIL_CACHE_MAX {
        CACHE.retain(|_, (ts, _)| ts.elapsed() < ttl);
    }
    CACHE.insert(model_name.to_string(), (std::time::Instant::now(), result));
    result
}

fn all_shards_available_inner(state: &AppState, model_name: &str) -> bool {
    let model_id = ModelId(model_name.to_string());

    let manifest = match state.shared_state.model_registry.get_manifest(&model_id) {
        Some(m) => m,
        None => {
            tracing::debug!(model = %model_name, "all_shards_available: no manifest");
            return false;
        }
    };

    // Need a valid layer count for the scheduler to work
    if manifest.num_layers == 0 {
        tracing::debug!(model = %model_name, "all_shards_available: num_layers=0");
        return false;
    }

    let total = manifest.shards.len();
    let mut covered = 0;
    for shard_info in &manifest.shards {
        let shard_id = crate::types::ShardId {
            model_id: model_id.clone(),
            index: shard_info.index,
        };
        let holders = state.shared_state.model_registry.shard_holders(&shard_id);
        if holders.is_empty() {
            tracing::debug!(
                model = %model_name,
                shard = shard_info.index,
                "all_shards_available: no node in network holds this shard"
            );
            return false;
        }
        covered += 1;
    }

    tracing::debug!(
        model = %model_name,
        shards = total,
        covered,
        num_layers = manifest.num_layers,
        "all_shards_available: all layers covered across network"
    );
    true
}

/// Resolve a model name for inference: handles "auto" alias and display-name → registry-ID mapping.
///
/// 1. If a local model is loaded and the request matches (by "auto", registry ID, or display name),
///    returns the resolved registry ID.
/// 2. For "auto" with no loaded model, falls back to the first model in the registry.
/// 3. Otherwise returns the original model name unchanged.
pub async fn resolve_model_for_inference(state: &AppState, model: &str) -> String {
    let info = state.shared_state.loaded_model_info.read().await;
    if let Some(i) = info.as_ref() {
        let resolved = resolve_loaded_model_registry_id(state, &i.name);
        if model == "auto" || model == resolved || model == i.name {
            return resolved;
        }
    }
    if model == "auto" {
        if let Some(m) = state
            .shared_state
            .model_registry
            .models()
            .into_iter()
            .next()
        {
            return m.id.0.clone();
        }
    }
    model.to_string()
}

/// Resolve a loaded model's display name to its registry ID.
///
/// Looks up the model in the registry by slug, then by display name.
/// Returns the registry ID if found, otherwise returns the slugified name.
pub fn resolve_loaded_model_registry_id(state: &AppState, model_display_name: &str) -> String {
    let slug = crate::types::slugify_model_name(model_display_name);
    state
        .shared_state
        .model_registry
        .get_manifest(&crate::types::ModelId(slug.clone()))
        .map(|m| m.id.0.clone())
        .or_else(|| {
            state
                .shared_state
                .model_registry
                .models()
                .into_iter()
                .find(|m| m.name == model_display_name)
                .map(|m| m.id.0.clone())
        })
        .unwrap_or(slug)
}

/// Check if a requested model matches the currently loaded model.
///
/// Returns true if the request matches by slug, display name, or registry ID.
pub fn model_matches_loaded(state: &AppState, loaded_name: &str, requested: &str) -> bool {
    let slug = crate::types::slugify_model_name(loaded_name);
    requested == slug
        || requested == loaded_name
        || state
            .shared_state
            .model_registry
            .get_manifest(&crate::types::ModelId(requested.to_string()))
            .is_some()
}

/// Resolve the model name to look up for inference (returns display name if available).
///
/// Checks loaded_model_info cache first, verifying it matches the request.
/// Falls back to manifest registry. Used by openai and anthropic handlers.
pub async fn resolve_model_name(state: &AppState, requested_model: &str) -> Option<String> {
    let info = state.shared_state.loaded_model_info.read().await;
    let cached_name = info.as_ref().map(|i| i.name.clone());
    let matches_request = info.as_ref().is_some_and(|i| {
        let slug = crate::types::slugify_model_name(&i.name);
        slug == requested_model || i.name == requested_model
    });
    drop(info);
    if matches_request {
        cached_name
    } else {
        state
            .shared_state
            .model_registry
            .get_manifest(&crate::types::ModelId(requested_model.to_string()))
            .map(|m| m.name.clone())
    }
}

/// Metadata extracted from a split model entry for prompt building.
pub struct SplitModelMeta {
    pub chat_template: Option<String>,
    pub bos_token: String,
    pub eos_token_str: String,
    pub layer_range: (u32, u32),
}

/// Look up split model metadata by model ID. Used by openai and anthropic handlers.
pub fn get_split_model_meta(
    state: &AppState,
    model_id: &crate::types::ModelId,
) -> Option<SplitModelMeta> {
    state
        .shared_state
        .split_models
        .iter()
        .find(|e| e.key().0 == *model_id)
        .map(|entry| {
            let e = entry.value();
            SplitModelMeta {
                chat_template: e.cached_chat_template.clone(),
                bos_token: e.bos_token.clone(),
                eos_token_str: e.eos_token_str.clone(),
                layer_range: (e.layer_start as u32, e.layer_end as u32),
            }
        })
}

/// Spawn a split-model generation task and return the token receiver.
///
/// Resolves model metadata, builds the prompt, and spawns the worker subprocess.
/// Returns None if the model is not loaded as a split model.
pub fn spawn_split_stream(
    state: &AppState,
    model_id: &crate::types::ModelId,
    messages: &[crate::types::ChatMessage],
    params: crate::types::SamplingParams,
    request_id: &str,
) -> Option<tokio::sync::mpsc::Receiver<crate::inference::router::StreamingTokenEvent>> {
    let meta = get_split_model_meta(state, model_id)?;
    let prompt = crate::inference::chat_template::build_prompt(
        messages,
        meta.chat_template.as_deref(),
        &meta.bos_token,
        &meta.eos_token_str,
    );
    let rid = uuid::Uuid::parse_str(request_id).unwrap_or_else(|_| uuid::Uuid::new_v4());
    let (token_tx, token_rx) =
        tokio::sync::mpsc::channel::<crate::inference::router::StreamingTokenEvent>(64);
    let pool = state.shared_state.model_process_pool.clone();
    let model_id = model_id.clone();
    let layer_range = meta.layer_range;
    tokio::spawn(async move {
        let _ = pool
            .generate(
                &model_id,
                layer_range,
                prompt,
                params,
                rid,
                None,
                Some(token_tx),
            )
            .await;
    });
    Some(token_rx)
}

/// Submit a streaming inference request to the router.
///
/// Creates the InferenceRequest and sends StreamSubmit. Returns receivers for
/// the final result and streaming tokens. Used by both openai and anthropic handlers.
pub async fn submit_stream_to_router(
    router_tx: &tokio::sync::mpsc::Sender<RouterCommand>,
    model_id: ModelId,
    messages: Vec<ChatMessage>,
    sampling_params: SamplingParams,
    session_id: Option<String>,
    lora_adapter: Option<String>,
) -> Result<
    (
        tokio::sync::oneshot::Receiver<
            Result<crate::inference::router::InferenceOutput, crate::error::SwarmError>,
        >,
        tokio::sync::mpsc::Receiver<StreamingTokenEvent>,
    ),
    ApiError,
> {
    let (result_tx, result_rx) = tokio::sync::oneshot::channel();
    let (token_tx, token_rx) = tokio::sync::mpsc::channel::<StreamingTokenEvent>(64);

    let inference_req = InferenceRequest::local(
        model_id,
        messages,
        sampling_params,
        true,
        session_id,
        lora_adapter,
    );

    router_tx
        .send(RouterCommand::StreamSubmit {
            request: inference_req,
            result_tx,
            token_tx,
        })
        .await
        .map_err(|_| {
            ApiError(crate::error::SwarmError::ServiceUnavailable(
                "Router unavailable".into(),
            ))
        })?;

    Ok((result_rx, token_rx))
}

/// Run non-streaming inference on a local split model.
///
/// Shared core for both OpenAI and Anthropic split_non_stream handlers.
/// Resolves model metadata, builds the prompt, and runs generation via subprocess.
pub async fn run_split_generate(
    state: &AppState,
    model_id: &crate::types::ModelId,
    messages: &[ChatMessage],
    params: SamplingParams,
    request_id: &str,
) -> Result<crate::inference::router::InferenceOutput, ApiError> {
    let meta = get_split_model_meta(state, model_id)
        .ok_or(ApiError(crate::error::SwarmError::NoModelLoaded))?;

    let prompt = chat_template::build_prompt(
        messages,
        meta.chat_template.as_deref(),
        &meta.bos_token,
        &meta.eos_token_str,
    );

    tracing::debug!(
        request_id = %request_id,
        prompt_len = prompt.len(),
        "DIAG: non-stream built prompt (subprocess)"
    );

    let rid = uuid::Uuid::parse_str(request_id).unwrap_or_else(|_| uuid::Uuid::new_v4());
    state
        .shared_state
        .model_process_pool
        .generate(model_id, meta.layer_range, prompt, params, rid, None, None)
        .await
        .map_err(ApiError)
}

/// Decode token IDs to text using the split model's tokenizer.
///
/// Uses BPE tokenizer byte decoding for proper UTF-8 handling (GPT-2 byte
/// encoding, SentencePiece byte fallbacks, etc).
fn peer_http_url(peer: &crate::types::PeerInfo) -> Option<String> {
    // Prefer UDP port (QUIC port == HTTP API port per convention),
    // fall back to TCP port - 10 (P2P TCP = HTTP + 10).
    let mut best_ip = None;
    let mut best_port = None;
    let mut have_udp = false;

    for addr in &peer.addresses {
        let parts: Vec<&str> = addr.split('/').collect();
        let mut ip = None;
        let mut udp_port = None;
        let mut tcp_port = None;
        for i in 0..parts.len() {
            if parts[i] == "ip4" && i + 1 < parts.len() {
                ip = Some(parts[i + 1]);
            }
            if parts[i] == "udp" && i + 1 < parts.len() {
                udp_port = Some(parts[i + 1]);
            }
            if parts[i] == "tcp" && i + 1 < parts.len() {
                tcp_port = Some(parts[i + 1]);
            }
        }
        if let Some(ip_str) = ip {
            if let Ok(parsed) = ip_str.parse::<std::net::Ipv4Addr>() {
                // Skip loopback, unspecified, and private IP ranges to prevent
                // SSRF via gossip-controlled peer addresses
                if parsed.is_loopback()
                    || parsed.is_unspecified()
                    || parsed.is_private()
                    || parsed.is_link_local()
                {
                    continue;
                }
            }
            // UDP port == HTTP API port (preferred)
            if let Some(port_str) = udp_port {
                if !have_udp {
                    best_ip = Some(ip_str.to_string());
                    best_port = Some(port_str.to_string());
                    have_udp = true;
                }
            }
            // TCP port = HTTP + 10, so HTTP = TCP - 10
            if let Some(port_str) = tcp_port {
                if !have_udp {
                    if let Ok(p) = port_str.parse::<u16>() {
                        best_ip = Some(ip_str.to_string());
                        best_port = Some(p.saturating_sub(10).to_string());
                    }
                }
            }
        }
    }
    match (best_ip, best_port) {
        (Some(ip), Some(port)) => Some(format!("http://{}:{}", ip, port)),
        _ => None,
    }
}

/// Forward a chat completion request to a peer's HTTP API.
/// Lazily-initialized shared reqwest client for peer forwarding.
/// Avoids creating a new TLS + connection pool on every request.
static PEER_CLIENT: std::sync::LazyLock<reqwest::Client> = std::sync::LazyLock::new(|| {
    reqwest::Client::builder()
        .connect_timeout(std::time::Duration::from_secs(10))
        .timeout(std::time::Duration::from_secs(
            INFERENCE_FORWARD_TIMEOUT_SECS,
        ))
        .build()
        .unwrap_or_else(|_| reqwest::Client::new())
});

fn get_peer_client() -> &'static reqwest::Client {
    &PEER_CLIENT
}

async fn forward_to_peer(
    peer_url: &str,
    req: &ChatCompletionRequest,
    stream: bool,
) -> Result<axum::response::Response, ApiError> {
    let client = get_peer_client();
    let url = format!("{}/v1/chat/completions", peer_url);

    let peer_resp = client
        .post(&url)
        .header("x-swarm-forwarded", "true")
        .json(req)
        .send()
        .await
        .map_err(|e| {
            tracing::warn!(error = %e, url = %url, "Failed to forward to peer");
            ApiError(crate::error::SwarmError::Network(format!(
                "Peer forwarding failed: {e}"
            )))
        })?;

    if !peer_resp.status().is_success() {
        let status = peer_resp.status();
        let raw_body = peer_resp.text().await.unwrap_or_default();
        let body = super::scrub_truncate_error(&raw_body);
        tracing::warn!(status = %status, body = %body, "Peer returned error");
        return Err(ApiError(crate::error::SwarmError::ProviderError {
            status: status.as_u16(),
            body,
        }));
    }

    let response = crate::api::providers::build_passthrough_response(peer_resp, stream).await?;
    Ok(response.into_response())
}

