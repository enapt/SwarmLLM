// ---- Request types ----

#[derive(Debug, Serialize, Deserialize)]
pub struct ChatCompletionRequest {
    pub model: String,
    pub messages: Vec<ApiChatMessage>,
    #[serde(default = "default_temperature")]
    pub temperature: f32,
    #[serde(default = "default_top_p")]
    pub top_p: f32,
    /// Upper bound on generated tokens. Accept either `max_tokens` (legacy)
    /// or `max_completion_tokens` (the spelling current OpenAI SDKs default to
    /// for o-series / gpt-5 reasoning models). Without this alias, a caller
    /// targeting a reasoning model through our proxy silently gets the 2048
    /// default, and reasoning tokens eat the whole budget before any content
    /// is emitted.
    #[serde(default = "default_max_tokens", alias = "max_completion_tokens")]
    pub max_tokens: u32,
    #[serde(default)]
    pub stream: bool,
    #[serde(default)]
    pub stop: Option<StopSequence>,
    #[serde(default)]
    pub frequency_penalty: f32,
    #[serde(default)]
    pub presence_penalty: f32,
    /// Tool definitions for function calling (OpenAI-compatible).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tools: Option<Vec<ToolDefinition>>,
    /// Controls which tool the model calls: "none", "auto", or {"type":"function","function":{"name":"..."}}.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_choice: Option<serde_json::Value>,
    /// Whether to return log probabilities for output tokens.
    #[serde(default)]
    pub logprobs: bool,
    /// Number of top log probabilities to return per token (0-20). Requires logprobs=true.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub top_logprobs: Option<u32>,
    /// Structured output format. Supports:
    /// - `{"type": "json_object"}` — model outputs valid JSON
    /// - `{"type": "json_schema", "json_schema": {"name": "...", "schema": {...}}}` — constrained to schema
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub response_format: Option<ResponseFormat>,
    /// Optional session ID for multi-turn KV-cache reuse.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub session_id: Option<String>,
    /// Optional LoRA adapter ID for per-request fine-tuned inference (SwarmLLM extension).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub lora_adapter: Option<String>,
    /// Optional cache control hints for prefix caching (Anthropic-compatible).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cache_control: Option<CacheControl>,
    /// Catch-all for OpenAI request fields we don't explicitly model
    /// (`reasoning_effort`, `service_tier`, `seed`, `metadata`, `store`,
    /// `parallel_tool_calls`, `stream_options`, `prediction`, …).
    /// `#[serde(flatten)]` preserves them verbatim through the round-trip, so
    /// the cloud-proxy path (handlers::try_cloud_proxy → serde_json::to_value)
    /// forwards the original caller's knobs instead of silently dropping
    /// anything unknown to our struct.
    #[serde(flatten)]
    pub extras: std::collections::HashMap<String, serde_json::Value>,
}

/// Cache control hints for prefix caching (Anthropic-compatible).
