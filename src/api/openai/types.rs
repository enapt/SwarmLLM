/// API-layer chat message supporting OpenAI's multimodal content format.
///
/// The `content` field can be either:
/// - A plain string: `"content": "Hello"`
/// - An array of content parts: `"content": [{"type": "text", "text": "..."}, {"type": "image_url", ...}]`
#[derive(Debug, Serialize, Deserialize)]
pub struct ApiChatMessage {
    pub role: crate::types::Role,
    #[serde(default, deserialize_with = "deserialize_nullable_content")]
    pub content: MessageContent,
    /// Tool calls generated by the assistant (present in assistant messages with tool use).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_calls: Option<Vec<ToolCall>>,
    /// The ID of the tool call this message is responding to (present in tool role messages).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub tool_call_id: Option<String>,
    /// Tool name (present in tool role messages).
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub name: Option<String>,
    /// Per-message cache control hint (Anthropic-compatible).
    /// Messages with `{"type": "ephemeral"}` mark the cache breakpoint.
    #[serde(default, skip_serializing_if = "Option::is_none")]
    pub cache_control: Option<CacheControl>,
}

/// OpenAI-compatible content field: either a plain string or an array of content parts.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(untagged)]
pub enum MessageContent {
    Text(String),
    Parts(Vec<ContentPart>),
}

/// Deserialize content that can be a string, array of parts, or null.
fn deserialize_nullable_content<'de, D>(deserializer: D) -> Result<MessageContent, D::Error>
where
    D: serde::Deserializer<'de>,
{
    let opt: Option<MessageContent> = Option::deserialize(deserializer)?;
    Ok(opt.unwrap_or_default())
}

impl Default for MessageContent {
    fn default() -> Self {
        Self::Text(String::new())
    }
}

/// A single content part in a multimodal message.
#[derive(Debug, Clone, Serialize, Deserialize)]
#[serde(tag = "type")]
pub enum ContentPart {
    #[serde(rename = "text")]
    Text { text: String },
    #[serde(rename = "image_url")]
    ImageUrl { image_url: ImageUrlRef },
}

/// Image URL reference — supports base64 data URIs.
#[derive(Debug, Clone, Serialize, Deserialize)]
pub struct ImageUrlRef {
    pub url: String,
}

/// Maximum allowed base64-encoded image size (20MB decoded).
const MAX_IMAGE_BASE64_BYTES: usize = 20 * 1024 * 1024;

impl ApiChatMessage {
    /// Convert to the internal `ChatMessage` type, decoding any base64 images.
    pub fn to_chat_message(&self) -> Result<ChatMessage, crate::error::SwarmError> {
        let (text, images) = match &self.content {
            MessageContent::Text(s) => (s.clone(), vec![]),
            MessageContent::Parts(parts) => {
                let mut text_parts = Vec::new();
                let mut images = Vec::new();
                for part in parts {
                    match part {
                        ContentPart::Text { text } => text_parts.push(text.clone()),
                        ContentPart::ImageUrl { image_url } => {
                            let img = decode_image_url(&image_url.url)?;
                            images.push(img);
                        }
                    }
                }
                (text_parts.join("\n"), images)
            }
        };

        Ok(ChatMessage {
            role: self.role.clone(),
            content: text,
            images,
        })
    }
}

impl ChatCompletionRequest {
    /// Convert API messages to internal ChatMessage format, decoding images.
    /// When tools or response_format are provided, injects system message(s).
    pub fn to_internal_messages(&self) -> Result<Vec<ChatMessage>, crate::error::SwarmError> {
        let mut messages: Vec<ChatMessage> = self
            .messages
            .iter()
            .map(|m| m.to_chat_message())
            .collect::<Result<_, _>>()?;

        // Inject structured output instructions
        if let Some(ref fmt) = self.response_format {
            let instruction = match fmt {
                ResponseFormat::Text => None,
                ResponseFormat::JsonObject => Some(
                    "You must respond with valid JSON only. Do not include any text \
                     outside the JSON object. Do not use markdown code blocks."
                        .to_string(),
                ),
                ResponseFormat::JsonSchema { json_schema } => {
                    let schema_str = serde_json::to_string_pretty(&json_schema.schema)
                        .unwrap_or_else(|_| json_schema.schema.to_string());
                    Some(format!(
                        "You must respond with valid JSON that conforms to the following schema. \
                         Do not include any text outside the JSON object. Do not use markdown code blocks.\n\n\
                         Schema name: {}\n\
                         Schema:\n{schema_str}",
                        json_schema.name
                    ))
                }
            };
            if let Some(inst) = instruction {
                messages.insert(
                    0,
                    ChatMessage {
                        role: crate::types::Role::System,
                        content: inst,
                        images: vec![],
                    },
                );
            }
        }

        // Inject tool definitions as a system message prefix — unless the
        // caller asked for no tool use. A local model only knows its tools
        // because they are described here, so "none" has to mean not
        // describing them; there is nowhere else to enforce it.
        if let Some(ref tools) = self.tools {
            if !tools.is_empty()
                && !crate::api::tool_parse::tool_choice_forbids_tools(&self.tool_choice)
            {
                let tool_desc = format_tool_system_prompt(tools);
                messages.insert(
                    0,
                    ChatMessage {
                        role: crate::types::Role::System,
                        content: tool_desc,
                        images: vec![],
                    },
                );
            }
        }

        Ok(messages)
    }

    pub(super) fn to_sampling_params(&self) -> SamplingParams {
        let stop = match &self.stop {
            Some(StopSequence::Single(s)) => vec![s.clone()],
            Some(StopSequence::Multiple(v)) => v.clone(),
            None => vec![],
        };
        crate::api::build_sampling_params(
            self.temperature,
            self.top_p,
            DEFAULT_TOP_K,
            self.max_tokens,
            stop,
            self.frequency_penalty,
            self.presence_penalty,
            self.logprobs,
            self.top_logprobs.unwrap_or(0),
        )
    }
}

/// Format tool definitions into the system prompt that tells a local model how
/// to request a tool call.
///
/// Thin adapter over [`crate::api::tool_parse::format_tool_prompt`], which is
/// shared with the Anthropic surface. The wording must stay identical across
/// both: [`crate::api::tool_parse::parse_tool_calls`] tries the requested shape
/// first, so two wordings would mean two formats to parse. This was a
/// byte-identical copy until 2026-07-26.
pub(super) fn format_tool_system_prompt(tools: &[ToolDefinition]) -> String {
    let specs: Vec<(String, Option<String>, Option<String>)> = tools
        .iter()
        .map(|t| {
            (
                t.function.name.clone(),
                t.function.description.clone(),
                t.function.parameters.as_ref().map(|p| p.to_string()),
            )
        })
        .collect();
    crate::api::tool_parse::format_tool_prompt(&specs)
}

/// Decode a base64 data URI image to raw RGB pixels.
fn decode_image_url(url: &str) -> Result<ImageData, crate::error::SwarmError> {
    let base64_data = if let Some(rest) = url.strip_prefix("data:") {
        if let Some(comma_pos) = rest.find(',') {
            let header = &rest[..comma_pos];
            if !header.contains("base64") {
                return Err(crate::error::SwarmError::Validation(
                    "Only base64 data URIs are supported for image_url".into(),
                ));
            }
            &rest[comma_pos + 1..]
        } else {
            return Err(crate::error::SwarmError::Validation(
                "Invalid data URI format".into(),
            ));
        }
    } else {
        return Err(crate::error::SwarmError::Validation(
            "Only data: URIs are supported for image_url (not remote URLs)".into(),
        ));
    };

    if base64_data.len() > MAX_IMAGE_BASE64_BYTES * 4 / 3 + 4 {
        return Err(crate::error::SwarmError::Validation(format!(
            "Image too large (max {}MB)",
            MAX_IMAGE_BASE64_BYTES / (1024 * 1024)
        )));
    }

    use base64::Engine;
    let bytes = base64::engine::general_purpose::STANDARD
        .decode(base64_data)
        .map_err(|e| crate::error::SwarmError::Validation(format!("Invalid base64 image: {e}")))?;

    if bytes.len() > MAX_IMAGE_BASE64_BYTES {
        return Err(crate::error::SwarmError::Validation(format!(
            "Decoded image too large: {}MB (max {}MB)",
            bytes.len() / (1024 * 1024),
            MAX_IMAGE_BASE64_BYTES / (1024 * 1024)
        )));
    }

    let img = image::load_from_memory(&bytes).map_err(|e| {
        crate::error::SwarmError::Validation(format!("Failed to decode image: {e}"))
    })?;

    let rgb = img.to_rgb8();
    let (width, height) = (rgb.width(), rgb.height());

    Ok(ImageData {
        rgb_bytes: rgb.into_raw(),
        width,
        height,
    })
}

